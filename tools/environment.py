"""Isolated PostgreSQL database clones for one benchmark attempt.

The seeded v2 database is treated as an immutable template.  Each attempt gets
two clones: a reference database for baseline timing and a candidate database
where the restricted index tools may operate.  Cleanup can only target names
generated by this module and carrying the fixture marker.
"""

from __future__ import annotations

import re
import uuid
from contextlib import contextmanager
from dataclasses import dataclass
from typing import Iterator

import psycopg
from psycopg import sql
from psycopg.conninfo import conninfo_to_dict, make_conninfo


DEFAULT_ADMIN_DSN = "postgresql://postgres@127.0.0.1:55433/postgres"
DEFAULT_FIXTURE_DATABASE = "sql_agent_fixture_v2"
FIXTURE_ID = "sql-agent-scaling-v2"
DATABASE_PREFIX = "sqlbench_"
_GENERATED_NAME = re.compile(r"^sqlbench_[0-9a-f]{12}_(?:ref|candidate)$")


def _dsn_with_database(dsn: str, database: str, *, user: str | None = None) -> str:
    values = conninfo_to_dict(dsn)
    values["dbname"] = database
    if user is not None:
        values["user"] = user
    return make_conninfo(**values)


@dataclass(frozen=True, slots=True)
class AttemptDatabases:
    """Connection details for an isolated baseline/candidate pair."""

    reference_dsn: str
    candidate_dsn: str
    candidate_controller_dsn: str
    reference_database: str
    candidate_database: str

    def make_reference_tools(self, baseline_sql: str, **kwargs):
        from .postgres import PostgresTools

        return PostgresTools(
            dsn=self.reference_dsn,
            baseline_sql=baseline_sql,
            freedom_profile="query_only",
            **kwargs,
        )

    def make_candidate_tools(self, baseline_sql: str, freedom_profile: str, **kwargs):
        from .postgres import PostgresTools

        return PostgresTools(
            dsn=self.candidate_dsn,
            controller_dsn=self.candidate_controller_dsn,
            baseline_sql=baseline_sql,
            freedom_profile=freedom_profile,
            **kwargs,
        )


class DatabaseEnvironment:
    """Create and remove verified database clones for benchmark attempts."""

    def __init__(
        self,
        admin_dsn: str = DEFAULT_ADMIN_DSN,
        fixture_database: str = DEFAULT_FIXTURE_DATABASE,
    ) -> None:
        self.admin_dsn = admin_dsn
        self.fixture_database = fixture_database
        if not re.fullmatch(r"[a-z][a-z0-9_]{0,62}", fixture_database):
            raise ValueError("fixture_database must be a simple PostgreSQL identifier")

    def _verify_fixture(self, connection: psycopg.Connection, database: str) -> None:
        with psycopg.connect(
            _dsn_with_database(self.admin_dsn, database), connect_timeout=5
        ) as target:
            marker = target.execute(
                "SELECT fixture_id FROM public.benchmark_fixture_metadata"
            ).fetchone()
        if marker is None or marker[0] != FIXTURE_ID:
            raise RuntimeError(f"database {database!r} is not the v2 benchmark fixture")

    def _verify_template(self, connection: psycopg.Connection) -> None:
        row = connection.execute(
            """
            SELECT datallowconn, shobj_description(oid, 'pg_database')
            FROM pg_database WHERE datname = %s
            """,
            (self.fixture_database,),
        ).fetchone()
        if row is None or row[0] is not False or row[1] != FIXTURE_ID:
            raise RuntimeError(
                "fixture template must exist, be frozen, and carry the v2 marker"
            )

    def _create_clone(self, connection: psycopg.Connection, name: str) -> None:
        connection.execute(
            # FILE_COPY avoids generating roughly one fixture-size worth of WAL
            # for every clone.  This is both faster and more reliable on Docker
            # Desktop's virtual disk than PostgreSQL's default WAL_LOG strategy.
            sql.SQL("CREATE DATABASE {} TEMPLATE {} STRATEGY FILE_COPY").format(
                sql.Identifier(name), sql.Identifier(self.fixture_database)
            )
        )
        self._verify_fixture(connection, name)

    def _drop_clone(self, connection: psycopg.Connection, name: str) -> None:
        if not _GENERATED_NAME.fullmatch(name):
            raise RuntimeError(f"refusing to drop non-generated database {name!r}")
        self._verify_fixture(connection, name)
        connection.execute(
            "SELECT pg_terminate_backend(pid) FROM pg_stat_activity "
            "WHERE datname = %s AND pid <> pg_backend_pid()",
            (name,),
        )
        connection.execute(sql.SQL("DROP DATABASE {}").format(sql.Identifier(name)))

    @contextmanager
    def attempt(self) -> Iterator[AttemptDatabases]:
        token = uuid.uuid4().hex[:12]
        reference = f"{DATABASE_PREFIX}{token}_ref"
        candidate = f"{DATABASE_PREFIX}{token}_candidate"
        created: list[str] = []
        with psycopg.connect(self.admin_dsn, autocommit=True, connect_timeout=5) as admin:
            self._verify_template(admin)
            try:
                for name in (reference, candidate):
                    self._create_clone(admin, name)
                    created.append(name)
                yield AttemptDatabases(
                    reference_dsn=_dsn_with_database(self.admin_dsn, reference, user="sql_agent"),
                    candidate_dsn=_dsn_with_database(self.admin_dsn, candidate, user="sql_agent"),
                    candidate_controller_dsn=_dsn_with_database(self.admin_dsn, candidate),
                    reference_database=reference,
                    candidate_database=candidate,
                )
            finally:
                for name in reversed(created):
                    self._drop_clone(admin, name)
